import fs from "node:fs";
import path from "node:path";

const read = (root: string, rel: string) => fs.readFileSync(path.join(root, rel), "utf8");

/** The keys of one interface in channels.ts. */
export function tableKeys(name: "Invoke" | "Push", repoRoot: string): Set<string> {
  const text = read(repoRoot, "packages/protocol/src/channels.ts");
  const body = text.match(new RegExp(`export interface ${name} \\{([\\s\\S]*?)\\n\\}`))?.[1] ?? "";
  return new Set([...body.matchAll(/^\s*"(hh:[A-Za-z]+)"\s*:/gm)].map((m) => m[1]));
}

/** The top-level keys of `AppConfig` in views.ts. */
export function configKeys(repoRoot: string): string[] {
  const text = read(repoRoot, "packages/protocol/src/views.ts");
  const body = text.match(/export interface AppConfig \{([\s\S]*?)\n\}/)?.[1] ?? "";
  return [...body.matchAll(/^ {2}(\w+)\??:/gm)].map((m) => m[1]);
}

export interface DocSource {
  path: string;
  text: string;
}

/** Every architecture doc except the generated contract, and every mod README. */
export function docSources(repoRoot: string): DocSource[] {
  const rels: string[] = [];
  const arch = path.join(repoRoot, "docs/architecture");
  if (fs.existsSync(arch)) {
    for (const f of fs.readdirSync(arch)) if (f.endsWith(".md") && f !== "contract.md") rels.push(`docs/architecture/${f}`);
  }
  const mods = path.join(repoRoot, "packages/mods");
  if (fs.existsSync(mods)) {
    for (const d of fs.readdirSync(mods, { withFileTypes: true })) {
      const rel = `packages/mods/${d.name}/README.md`;
      if (d.isDirectory() && fs.existsSync(path.join(repoRoot, rel))) rels.push(rel);
    }
  }
  return rels.sort().map((p) => ({ path: p, text: read(repoRoot, p) }));
}

/** The repo-relative paths of the sources that name `name` (spec §3). */
export function whereDocumented(name: string, kind: "channel" | "config", sources: DocSource[]): string[] {
  const re =
    kind === "channel" ? new RegExp("`" + name + "`") : new RegExp("`config\\.json`\\s*(?:→|->)\\s*`" + name + "`");
  return sources.filter((s) => re.test(s.text)).map((s) => s.path);
}

function link(p: string): string {
  const inArch = p.startsWith("docs/architecture/");
  const rel = inArch ? p.slice("docs/architecture/".length) : `../../${p}`;
  const label = inArch ? rel : p.replace(/^packages\/mods\//, "mods/").replace(/\/README\.md$/, "");
  return `[${label}](${rel})`;
}

function table(title: string, names: Iterable<string>, kind: "channel" | "config", sources: DocSource[]): string {
  const rows = [...names].sort().map((n) => {
    const where = whereDocumented(n, kind, sources);
    return `| \`${n}\` | ${where.length ? where.map(link).join(", ") : "—"} |`;
  });
  return [`## ${title}`, "", "| Name | Documented in |", "|---|---|", ...rows, ""].join("\n");
}

/** The whole text of docs/architecture/contract.md. */
export function renderContract(repoRoot: string): string {
  const sources = docSources(repoRoot);
  return [
    "Generated by `pnpm docs:gen` from `channels.ts` and `AppConfig`. Do not edit.",
    "",
    "# Contract: IPC channels and config keys",
    "",
    table("Invoke channels", tableKeys("Invoke", repoRoot), "channel", sources),
    table("Push channels", tableKeys("Push", repoRoot), "channel", sources),
    table("`config.json` keys", configKeys(repoRoot), "config", sources),
  ].join("\n");
}
