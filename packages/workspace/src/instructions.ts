/** A folder the agent may read but never change, with the label the instructions show. */
export interface ReferenceFolder {
  label: string;
  path: string;
}

function toolSchema(schema: Block["schema"]): string {
  const { $schema: _omit, ...rest } = z.toJSONSchema(schema) as Record<string, unknown>;
  return JSON.stringify(rest);
}

export function managedSection(opts: { language: Language; blocks: Record<string, Block>; references?: ReferenceFolder[] }): string {
  const t = TEXT[opts.language];
  const lines = [MANAGED_START, t.title, "", ...t.rules.map((r) => `- ${r}`)];
  const entries = Object.entries(opts.blocks);
  if (entries.length > 0) {
    lines.push("", t.tools, "", t.toolsIntro, "");
    for (const [name, block] of entries) {
      lines.push(
        `- \`${blockToolName(name, block)}\`: ${block.description}`,
        `  ${t.example}: \`${JSON.stringify(block.example)}\``,
        `  ${t.schema}: \`${toolSchema(block.schema)}\``,
      );
      if (block.input) lines.push(`  ${t.answer}: \`${toolSchema(block.input)}\``);
    }
    // Only a harness with input blocks gets the answers section (spec D0).
    if (entries.some(([, b]) => b.input)) {
      lines.push("", t.answers, "", ...t.answerRules.map((r) => `- ${r}`));
      if (Object.hasOwn(opts.blocks, "annotate")) lines.push(`- ${t.annotateRule}`);
    }
  }
  const references = opts.references ?? [];
  if (references.length > 0) {
    lines.push("", t.references, "", t.referencesIntro, "");
    for (const r of references) lines.push(`- ${r.label}: \`${r.path}\``);
  }
  lines.push(MANAGED_END, "");
  return lines.join("\n");
}

/** The files the app generates in the folder for an engine: AGENTS.md and the engine's own instructions file. */
export function generatedFiles(engine: EngineDef): string[] {
  return ["AGENTS.md", ...(engine.instructionsFile ? [engine.instructionsFile.path] : [])];
}

/** Writes AGENTS.md (harness base + managed section) and the engine's own file. Returns the relative paths written. */
export async function writeInstructions(opts: {
  folder: string;
  base: string;
  language: Language;
  blocks: Record<string, Block>;
  references?: ReferenceFolder[];
  engine: EngineDef;
}): Promise<string[]> {
  const extraPath = opts.engine.instructionsFile?.path;
  if (extraPath !== undefined && path.basename(extraPath) !== extraPath) {
    throw new Error(`Engine instructions file must be a plain file name, got "${extraPath}"`);
  }
  await fs.mkdir(opts.folder, { recursive: true });
  const agents = `${opts.base.trimEnd()}\n\n${managedSection({ language: opts.language, blocks: opts.blocks, references: opts.references })}`;
  await fs.writeFile(path.join(opts.folder, "AGENTS.md"), agents);
  const extra = opts.engine.instructionsFile;
  if (extra) await fs.writeFile(path.join(opts.folder, extra.path), extra.content);
  return generatedFiles(opts.engine);
}
