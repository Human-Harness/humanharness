import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { configKeys, docSources, renderContract, tableKeys, whereDocumented } from "./contract-docs";

const src = (text: string, p = "docs/architecture/x.md") => [{ path: p, text }];

describe("whereDocumented", () => {
  it("counts a channel in backticks, not in plain text", () => {
    expect(whereDocumented("hh:pauseTask", "channel", src("Use `hh:pauseTask` here."))).toEqual(["docs/architecture/x.md"]);
    expect(whereDocumented("hh:pauseTask", "channel", src("Use hh:pauseTask here."))).toEqual([]);
  });

  it("counts config.json → key and ->, not a bare key", () => {
    expect(whereDocumented("language", "config", src("`config.json` → `language`: x"))).toHaveLength(1);
    expect(whereDocumented("language", "config", src("`config.json` -> `language`: x"))).toHaveLength(1);
    expect(whereDocumented("language", "config", src("the `language` key"))).toEqual([]);
  });
});

describe("fixtures in a temp repo", () => {
  const roots: string[] = [];
  afterEach(() => {
    for (const r of roots.splice(0)) fs.rmSync(r, { recursive: true, force: true });
  });
  function repo(files: Record<string, string>): string {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "contract-docs-"));
    roots.push(root);
    const all: Record<string, string> = {
      "packages/protocol/src/channels.ts":
        'export interface Invoke {\n  "hh:zeta": { a: 1 };\n  "hh:alpha": { a: 1 };\n}\nexport interface Push {\n  "hh:beat": number;\n}\n',
      "packages/protocol/src/views.ts": "export interface AppConfig {\n  language?: string;\n  /** c */\n  folder?: string;\n}\n",
      ...files,
    };
    for (const [p, text] of Object.entries(all)) {
      fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
      fs.writeFileSync(path.join(root, p), text);
    }
    return root;
  }

  it("reads tables and config keys", () => {
    const root = repo({});
    expect([...tableKeys("Invoke", root)]).toEqual(["hh:zeta", "hh:alpha"]);
    expect([...tableKeys("Push", root)]).toEqual(["hh:beat"]);
    expect(configKeys(root)).toEqual(["language", "folder"]);
  });

  it("never takes contract.md as a source; takes mod READMEs", () => {
    const root = repo({
      "docs/architecture/contract.md": "`hh:zeta`",
      "docs/architecture/a.md": "`hh:alpha`",
      "packages/mods/m1/README.md": "`hh:zeta`",
    });
    const s = docSources(root);
    expect(s.map((x) => x.path).sort()).toEqual(["docs/architecture/a.md", "packages/mods/m1/README.md"]);
    expect(whereDocumented("hh:zeta", "channel", s)).toEqual(["packages/mods/m1/README.md"]);
    expect(renderContract(root)).toContain("(../../packages/mods/m1/README.md)");
  });

  it("renders sorted rows, a dash for no doc, and the header", () => {
    const root = repo({ "docs/architecture/a.md": "`hh:alpha`" });
    const out = renderContract(root);
    expect(out.startsWith("Generated by `pnpm docs:gen`")).toBe(true);
    expect(out).toContain("Do not edit.");
    expect(out.indexOf("| `hh:alpha`")).toBeLessThan(out.indexOf("| `hh:zeta`"));
    expect(out).toContain("| `hh:zeta` | — |");
    expect(out).toContain("| `hh:alpha` | [a.md](a.md) |");
  });
});
