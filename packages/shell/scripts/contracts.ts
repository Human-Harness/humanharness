// Compares today's hh.d.ts with the frozen copy in packages/mod-sdk/released/ (published-contract snapshots spec).
// Run with `corepack pnpm --filter @humanharness/shell contracts check|accept`.
//
// The frozen copy's modules are renamed to `@hh-frozen/…`, so both versions load in one program, and a generated
// check.ts asserts, one line per public name, that the change is safe for whoever is on the other side of it:
// `host` types (the app hands them to mods) may only grow, `mod` types (mods hand them to the app) may only loosen,
// `both` may not change, values may only accept more. A failed assertion is a breaking change.
import { execFileSync } from "node:child_process";
import { existsSync, promises as fs, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
// @ts-expect-error TS5097: plain `node` runs this script and needs the extension; the repo's tsconfig does not allow it.
import { HH_DTS_FILE, publicNames, publicNamesByModule, tscBin } from "./hh-dts.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const PACKAGES = path.resolve(here, "../..");

export type Role = "host" | "mod" | "both";
export type Verdict = { result: "same" | "additive" | "breaking"; names: string[] };
type Kind = "value" | "type";
type Module = "mod-sdk" | "ui";

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Which public module exports each name (mod-sdk first). */
function moduleOf(dts: string): Map<string, Module> {
  const by = publicNamesByModule(dts);
  const out = new Map<string, Module>();
  for (const n of by.ui) out.set(n, "ui");
  for (const n of by["mod-sdk"]) out.set(n, "mod-sdk");
  return out;
}

/** Value or type, by the declaration that exports the name somewhere in the file. */
export function kindsOf(dts: string, names: string[]): Map<string, Kind> {
  const out = new Map<string, Kind>();
  for (const n of names) {
    const v = new RegExp(`^\\s*export\\s+(?:declare\\s+)?(?:(?:async\\s+)?function|const|let|var|(?:abstract\\s+)?class|enum)\\s+${escape(n)}\\b|^\\s*export\\s+\\*\\s+as\\s+${escape(n)}\\s+from`, "m");
    const t = new RegExp(`^\\s*export\\s+(?:declare\\s+)?(?:type|interface)\\s+${escape(n)}\\b`, "m");
    // A name with neither is checked as a value: if it is a type, `typeof` fails to compile and says so.
    out.set(n, v.test(dts) || !t.test(dts) ? "value" : "type");
  }
  return out;
}

/** The frozen copy's own modules renamed to `@hh-frozen/…`; imports of other packages stay as they are. */
export function renameFrozen(dts: string): string {
  const own = new Set([...dts.matchAll(/^declare module "([^"]+)"/gm)].map((m) => m[1]));
  return dts.replace(/(["'])(@humanharness\/[^"']+)\1/g, (all, q: string, name: string) =>
    own.has(name) ? `${q}@hh-frozen/${name.slice("@humanharness/".length)}${q}` : all,
  );
}

/** The text of every top-level statement in the file's modules that declares `name`, whitespace-collapsed. */
function declarationText(dts: string, name: string): string {
  const head = new RegExp(`^ {2}export\\s+(?:declare\\s+)?(?:(?:async\\s+)?function|const|let|var|(?:abstract\\s+)?class|enum|type|interface|namespace)\\s+${escape(name)}\\b`);
  const out: string[] = [];
  let current: string[] | null = null;
  for (const line of dts.split("\n")) {
    // A statement starts at two-space indentation, unless the line closes or continues the one before.
    const starts = /^ {2}[^ }\])|&]/.test(line) || /^\S/.test(line);
    if (starts) {
      if (current) out.push(current.join(" "));
      current = head.test(line) ? [line] : null;
    } else if (current) current.push(line);
  }
  if (current) out.push(current.join(" "));
  return out.join("\n").replace(/\s+/g, " ").trim();
}

const HEADER = [
  "// generated by contracts.ts — one line per name, so a diagnostic's line maps back to its name",
  'import type { z } from "zod";',
  'import type * as F from "@hh-frozen/mod-sdk";',
  'import type * as C from "@humanharness/mod-sdk";',
  'import type * as FU from "@hh-frozen/ui";',
  'import type * as CU from "@humanharness/ui";',
  "type Strict<T> = T extends (...a: infer A) => infer R",
  "  ? (...a: { [I in keyof A]: Strict<A[I]> }) => Strict<R>",
  "  : T extends object ? { [K in keyof T]: Strict<T[K]> } : T;",
  "type Assert<A extends B, B> = A;",
];

/** check.ts, and the name behind each of its lines (1-based). */
export function assertionFile(names: { name: string; kind: Kind; module: Module; role?: Role }[]): { text: string; lineNames: Map<number, string> } {
  const lines = [...HEADER];
  const lineNames = new Map<number, string>();
  const add = (name: string, a: string, b: string) => {
    lines.push(`type L${lines.length + 1} = Assert<${a}, ${b}>; // ${name}`);
    lineNames.set(lines.length, name);
  };
  for (const { name, kind, module, role } of names) {
    const [f, c] = module === "mod-sdk" ? ["F", "C"] : ["FU", "CU"];
    // mod-sdk sides go through Strict (method parameters are bivariant otherwise); ui's guide types are too big for it.
    const wrap = (t: string) => (module === "mod-sdk" ? `Strict<${t}>` : t);
    if (kind === "value") {
      if (name.endsWith("Schema")) add(name, wrap(`z.input<typeof ${f}.${name}>`), wrap(`z.input<typeof ${c}.${name}>`));
      else add(name, wrap(`typeof ${c}.${name}`), wrap(`typeof ${f}.${name}`));
      continue;
    }
    if (role === "host" || role === "both") add(name, wrap(`${c}.${name}`), wrap(`${f}.${name}`));
    if (role === "mod" || role === "both") add(name, wrap(`${f}.${name}`), wrap(`${c}.${name}`));
  }
  return { text: `${lines.join("\n")}\n`, lineNames };
}

/** The 1-based column of the first type argument on line `n` of check.ts. */
const ARG_COLUMN = (n: number) => `type L${n} = Assert<`.length + 1;

/** Where check.ts compiles: packages/shell/node_modules/.cache resolves the shell's packages; radix comes from ui's. */
async function makeTmp(): Promise<string> {
  const cache = path.join(PACKAGES, "shell", "node_modules", ".cache");
  await fs.mkdir(cache, { recursive: true });
  const tmp = await fs.mkdtemp(path.join(cache, "contracts-"));
  await fs.mkdir(path.join(tmp, "node_modules", "@radix-ui"), { recursive: true });
  await fs.symlink(path.join(PACKAGES, "ui", "node_modules", "@radix-ui", "themes"), path.join(tmp, "node_modules", "@radix-ui", "themes"), "dir");
  return tmp;
}

/** Compiles check.ts; returns the names whose assertion failed. Any other diagnostic throws with tsc's output. */
export function runCheckTsc(tmp: string, lineNames: Map<number, string>): Set<string> {
  const args = [
    tscBin(),
    "--ignoreConfig",
    "--noEmit",
    // The real packages load too (the ambient modules win for the check); ui's CSS imports have no declarations.
    "--noUncheckedSideEffectImports",
    "false",
    "--strict",
    "--skipLibCheck",
    "--target",
    "ES2023",
    "--module",
    "ESNext",
    "--moduleResolution",
    "bundler",
    "--jsx",
    "react-jsx",
    "--lib",
    "ES2023,DOM,DOM.Iterable",
    "--types",
    "node",
    "check.ts",
    "frozen.d.ts",
    "current.d.ts",
  ];
  let output = "";
  try {
    execFileSync(process.execPath, args, { cwd: tmp, stdio: "pipe" });
    return new Set();
  } catch (err) {
    const e = err as { stdout?: Buffer; stderr?: Buffer };
    output = `${String(e.stdout ?? "")}${String(e.stderr ?? "")}`;
  }
  const failed = new Set<string>();
  // tsc 7 reports a failed assertion by its elaborated error (TS2741, TS2322, …), not always TS2344, so the position
  // tells: an assertion fails at the start of its first type argument. Anything else (a missing name, an unresolved
  // import, an error in another file) is not a verdict.
  const isAssertion = (file: string, line: number, col: number) => file === "check.ts" && lineNames.has(line) && col === ARG_COLUMN(line);
  const diagnostics = [...output.matchAll(/^(.+?)\((\d+),(\d+)\): error (TS\d+):/gm)];
  const other = diagnostics.filter((d) => !isAssertion(d[1], Number(d[2]), Number(d[3])));
  if (diagnostics.length === 0 || other.length > 0) throw new Error(`contracts: the check did not compile:\n${output}`);
  for (const d of diagnostics) failed.add(lineNames.get(Number(d[2]))!);
  return failed;
}

/** The result from what was removed, what was added, what fails and what changed text. */
export function verdictFrom(v: { removed: string[]; added: string[]; failed: Set<string>; changed: string[] }): Verdict {
  const sorted = (xs: Iterable<string>) => [...new Set(xs)].sort();
  const breaking = sorted([...v.removed, ...v.failed]);
  if (breaking.length > 0) return { result: "breaking", names: breaking };
  const additive = sorted([...v.added, ...v.changed]);
  if (additive.length > 0) return { result: "additive", names: additive };
  return { result: "same", names: [] };
}

export async function compareHhDts(input: { frozen: string; current: string; roles: Record<string, Role> }): Promise<Verdict> {
  const frozenNames = moduleOf(input.frozen);
  const currentNames = moduleOf(input.current);
  const removed = [...frozenNames.keys()].filter((n) => !currentNames.has(n));
  const added = [...currentNames.keys()].filter((n) => !frozenNames.has(n));

  const kinds = kindsOf(input.current, [...currentNames.keys()]);
  const missing = [...kinds].filter(([n, k]) => k === "type" && !Object.hasOwn(input.roles, n)).map(([n]) => n).sort();
  if (missing.length > 0) {
    throw new Error(missing.map((n) => `${n} has no role: add it to packages/mod-sdk/released/roles.json as "host", "mod" or "both" (spec §3.2)`).join("\n"));
  }

  const both = [...currentNames.keys()].filter((n) => frozenNames.has(n)).sort();
  const { text, lineNames } = assertionFile(
    both.map((name) => ({ name, kind: kinds.get(name)!, module: currentNames.get(name)!, role: input.roles[name] })),
  );
  const tmp = await makeTmp();
  let failed: Set<string>;
  try {
    await fs.writeFile(path.join(tmp, "frozen.d.ts"), renameFrozen(input.frozen));
    await fs.writeFile(path.join(tmp, "current.d.ts"), input.current);
    await fs.writeFile(path.join(tmp, "check.ts"), text);
    failed = runCheckTsc(tmp, lineNames);
  } finally {
    await fs.rm(tmp, { recursive: true, force: true });
  }
  const changed = both.filter((n) => declarationText(input.frozen, n) !== declarationText(input.current, n));
  return verdictFrom({ removed, added, failed, changed });
}

/** The frozen contract: packages/mod-sdk/released/. */
export const RELEASED_DIR = path.join(PACKAGES, "mod-sdk", "released");
const CONTRACT_FILE = path.join(RELEASED_DIR, "contract.json");
const ROLES_FILE = path.join(RELEASED_DIR, "roles.json");
const frozenFile = (apiVersion: number) => path.join(RELEASED_DIR, `hh.v${apiVersion}.d.ts`);

export type Contract = { apiVersion: number; frozen: boolean };
export function readContract(): Contract {
  return JSON.parse(readFileSync(CONTRACT_FILE, "utf8")) as Contract;
}
const readRoles = (): Record<string, Role> => JSON.parse(readFileSync(ROLES_FILE, "utf8")) as Record<string, Role>;

/** Today's hh.d.ts against the frozen copy of the contract's version. */
export async function checkRepo(): Promise<Verdict> {
  const { apiVersion } = readContract();
  return compareHhDts({ frozen: readFileSync(frozenFile(apiVersion), "utf8"), current: readFileSync(HH_DTS_FILE, "utf8"), roles: readRoles() });
}

/** Freezes today's hh.d.ts as the contract's version and drops the roles of types no longer exported (frozen false only). */
export async function accept(): Promise<Verdict | null> {
  if (!existsSync(CONTRACT_FILE)) writeFileSync(CONTRACT_FILE, `${JSON.stringify({ apiVersion: 1, frozen: false } satisfies Contract, null, 2)}\n`);
  const { apiVersion, frozen } = readContract();
  if (frozen) throw new Error("contracts accept: contract.json says frozen is true; accepting a frozen contract is not supported yet");
  const current = readFileSync(HH_DTS_FILE, "utf8");
  const verdict = existsSync(frozenFile(apiVersion)) ? await checkRepo() : null;
  const names = publicNames(current);
  const types = new Set([...kindsOf(current, names)].filter(([, k]) => k === "type").map(([n]) => n));
  const roles = Object.fromEntries(Object.entries(readRoles()).filter(([n]) => types.has(n)).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(frozenFile(apiVersion), current);
  writeFileSync(ROLES_FILE, `${JSON.stringify(roles, null, 2)}\n`);
  return verdict;
}

function line(v: Verdict): string {
  return v.result === "same" ? "same" : `${v.result}: ${v.names.join(", ")}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const cmd = process.argv[2];
  if (cmd === "check") {
    const v = await checkRepo();
    console.log(line(v));
    process.exitCode = v.result === "same" ? 0 : 1;
  } else if (cmd === "accept") {
    const v = await accept();
    if (v?.result === "breaking") console.log(`warning: breaking changes accepted while frozen is false: ${v.names.join(", ")}`);
    console.log(`Wrote ${path.relative(process.cwd(), RELEASED_DIR)}${v ? ` (${line(v)})` : ""}`);
  } else {
    console.error("usage: contracts check|accept");
    process.exitCode = 2;
  }
}
