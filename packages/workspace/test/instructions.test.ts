import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { z } from "zod";
import { CORE_BLOCKS, INPUT_CORE_BLOCKS, defineBlock } from "@humanharness/harness-sdk";
import { getEngine } from "@humanharness/engines";
import { MANAGED_END, MANAGED_START, managedSection, refreshInstructions, settingsLines, writeInstructions, writingLines } from "../src";

const root = fs.mkdtempSync(path.join(os.tmpdir(), "hh-"));
afterAll(() => fs.rmSync(root, { recursive: true, force: true }));

const blocks = {
  note: defineBlock({
    description: "Shows a note.",
    visible: true,
    schema: z.object({ title: z.string() }),
    example: { title: "Hi" },
  }),
  progress: defineBlock({
    description: "Updates progress.",
    visible: false,
    schema: z.object({ percent: z.number() }),
    example: { percent: 10 },
  }),
};

const tmp = () => fs.mkdtempSync(path.join(root, "t-"));

describe("managedSection", () => {
  it("is delimited, always English, and says to think in English and write in the person's language", () => {
    const es = managedSection({ language: "es", blocks });
    expect(es.startsWith(MANAGED_START)).toBe(true);
    expect(es.trimEnd().endsWith(MANAGED_END)).toBe(true);
    expect(es).toContain("## Environment (generated by Human Harness; do not edit)");
    expect(es).toContain("- Think and reason in English.");
    expect(es).toContain("- Write everything the person sees in Spanish: your messages, choices, the content of interface blocks, and the files you write for them.");
    expect(es).toContain("- Notes you save with `save_note` are in English.");
    expect(managedSection({ language: "pt-BR", blocks })).toContain("in Brazilian Portuguese:");
  });

  it("the Material part only with material (material spec §9)", () => {
    const without = managedSection({ language: "en", blocks: {} });
    expect(without).not.toContain("### Material");
    const withIt = managedSection({ language: "en", blocks: {}, material: true });
    expect(withIt).toContain("### Material");
    expect(withIt).toContain("[[frag:<id>]]");
    expect(withIt).toContain("material_conflict");
    expect(withIt).toContain("never open the files under `.harness/material/`");
    expect(withIt.trimEnd().endsWith(MANAGED_END)).toBe(true);
  });

  it("documents every block tool with its example and schema", () => {
    const s = managedSection({ language: "en", blocks });
    expect(s).toContain("`show_note`");
    expect(s).toContain("`update_progress`");
    expect(s).toContain('{"title":"Hi"}');
    expect(s).toContain('"percent"');
    expect(s).not.toContain("$schema");
  });

  it("tells the agent its tools show up in call order, so it introduces each thing first", () => {
    expect(managedSection({ language: "en", blocks })).toContain("write the sentence that introduces each thing first, then call the tool");
  });

  it("leads the tools section with a one-line intro", () => {
    expect(managedSection({ language: "en", blocks })).toContain(
      "Call these tools to show things to the person or update their state.",
    );
  });

  it("documents the core blocks with their own tool names", () => {
    const s = managedSection({ language: "en", blocks: { ...CORE_BLOCKS, ...blocks } });
    expect(s).toContain("`show_choices`");
    expect(s).toContain("`save_note`");
    expect(s).not.toContain("update_save_note");
  });

  it("lists the reference folders as read only, and only when there are some", () => {
    const s = managedSection({ language: "es", blocks, references: [{ label: "Human Harness source", path: "/Users/me/code/hh" }] });
    expect(s).toContain("### Reference folders (read only)");
    expect(s).toContain("You may read these folders with your read tools. Never change anything in them.");
    expect(s).toContain("- Human Harness source: `/Users/me/code/hh`");
    expect(s.indexOf("Reference folders")).toBeLessThan(s.indexOf(MANAGED_END));
    expect(managedSection({ language: "en", blocks })).not.toContain("Reference folders");
  });
});

describe("writeInstructions", () => {
  it("writes AGENTS.md plus the engine's own file", async () => {
    const folder = tmp();
    const written = await writeInstructions({
      folder,
      base: "# Flow\n\nDo things.\n",
      language: "es",
      blocks,
      engine: getEngine("claude"),
    });
    expect(written.sort()).toEqual(["AGENTS.md", "CLAUDE.md"]);
    const agents = fs.readFileSync(path.join(folder, "AGENTS.md"), "utf8");
    expect(agents.startsWith("# Flow\n\nDo things.\n\n" + MANAGED_START)).toBe(true);
    expect(fs.readFileSync(path.join(folder, "CLAUDE.md"), "utf8")).toBe("@AGENTS.md\n");
  });

  it("writes only AGENTS.md for engines that read it directly", async () => {
    const folder = tmp();
    const written = await writeInstructions({ folder, base: "x", language: "en", blocks, engine: getEngine("codex") });
    expect(written).toEqual(["AGENTS.md"]);
    expect(fs.existsSync(path.join(folder, "CLAUDE.md"))).toBe(false);
  });

  it("rejects an engine file path that is not a plain file name", async () => {
    const engine = { ...getEngine("codex"), instructionsFile: { path: "../evil.md", content: "x" } };
    await expect(
      writeInstructions({ folder: tmp(), base: "x", language: "en", blocks, engine }),
    ).rejects.toThrow();
  });

  it("is idempotent", async () => {
    const folder = tmp();
    const opts = { folder, base: "x", language: "en" as const, blocks, engine: getEngine("codex") };
    await writeInstructions(opts);
    const first = fs.readFileSync(path.join(folder, "AGENTS.md"), "utf8");
    await writeInstructions(opts);
    expect(fs.readFileSync(path.join(folder, "AGENTS.md"), "utf8")).toBe(first);
  });

  it("writes the reference folders into AGENTS.md", async () => {
    const folder = tmp();
    await writeInstructions({ folder, base: "x", language: "en", blocks, references: [{ label: "Source", path: "/r" }], engine: getEngine("codex") });
    expect(fs.readFileSync(path.join(folder, "AGENTS.md"), "utf8")).toContain("- Source: `/r`");
  });
});

describe("managedSection: input blocks", () => {
  const schemaOf = (s: z.ZodObject) => {
    const { $schema: _omit, ...rest } = z.toJSONSchema(s) as Record<string, unknown>;
    return JSON.stringify(rest);
  };
  const ask = defineBlock({
    description: "Asks why.",
    visible: true,
    schema: z.object({ question: z.string() }),
    input: z.object({ why: z.string().min(1) }),
    example: { question: "q" },
  });

  it("D0: without input blocks the section is exactly today's", () => {
    expect(managedSection({ language: "en", blocks })).toBe(
      [
        MANAGED_START,
        "## Environment (generated by Human Harness; do not edit)",
        "",
        "- Think and reason in English.",
        "- Write everything the person sees in English: your messages, choices, the content of interface blocks, and the files you write for them.",
        "- Notes you save with `save_note` are in English.",
        "- You are running inside a desktop app: the person talks to you from an interface, not a terminal. Don't show commands or file paths unless asked.",
        "- Don't use your CLI's own interactive questions: ask in plain text or with the interface tools below.",
        "- Work only inside this folder. Keep messages short and clear.",
        "",
        "### Interface tools",
        "",
        "Call these tools to show things to the person or update their state. What they show appears in the conversation in the order you call them, among your text: write the sentence that introduces each thing first, then call the tool.",
        "",
        "- `show_note`: Shows a note.",
        '  Example: `{"title":"Hi"}`',
        `  Schema: \`${schemaOf(blocks.note.schema)}\``,
        "- `update_progress`: Updates progress.",
        '  Example: `{"percent":10}`',
        `  Schema: \`${schemaOf(blocks.progress.schema)}\``,
        MANAGED_END,
        "",
      ].join("\n"),
    );
  });

  it("documents each input block's answer and how answers come back", () => {
    const en = managedSection({ language: "en", blocks: { ...blocks, ask } });
    expect(en).toContain(
      `- \`show_ask\`: Asks why.\n  Example: \`{"question":"q"}\`\n  Schema: \`${schemaOf(ask.schema)}\`\n  Answer (\`[answer to ask]\`): \`${schemaOf(ask.input!)}\``,
    );
    expect(en).toContain(
      [
        "### Answers from input blocks",
        "",
        "- A tool with an `Answer` schema asks the person for something. After calling it, end your turn and wait: the answer comes as the next message.",
        "- That message starts with the header on the tool's `Answer` line (`[answer to <block>]`), then what the person sees, then a ```json block with `block`, `blockId` and `value`. Trust the JSON: `value` already matches the block's `Answer` schema.",
        '- When `value` is `{"skipped":true}`, the person skipped the question: go on without insisting.',
        "- The person may write in the chat instead of answering. The question stays open and may still be answered later: answer what they wrote, or remind them of the question.",
      ].join("\n"),
    );
    expect(en.match(/ {2}Answer \(/g)).toHaveLength(1);
    // Whatever the person's language, the answers section and the header are English (spec 5 D4).
    const es = managedSection({ language: "es", blocks: { ask } });
    expect(es).toContain(`  Answer (\`[answer to ask]\`): \`${schemaOf(ask.input!)}\``);
    expect(es).toContain("### Answers from input blocks");
    expect(es).not.toMatch(/Respuesta|respuesta a/);
  });

  it("a block with its own tool name still names its answer's header by the block", () => {
    const pick = defineBlock({ ...ask, tool: "choose_side" });
    const en = managedSection({ language: "en", blocks: { pick } });
    expect(en).toContain("- `choose_side`: Asks why.");
    expect(en).toContain(`  Answer (\`[answer to pick]\`): \`${schemaOf(ask.input!)}\``);
  });

  it("explains annotate only when the harness has it", () => {
    const line = '- To mark parts of an answer, call `show_annotate` with `ref` (the answer\'s `blockId`, or "last") and quote the person\'s exact words in each mark.';
    expect(managedSection({ language: "en", blocks: { ask } })).not.toContain("show_annotate");
    expect(managedSection({ language: "en", blocks: { ...INPUT_CORE_BLOCKS, ask } })).toContain(line);
  });
});

describe("managedSection: settings", () => {
  it("writes the sentences after the core rules and before the interface tools", () => {
    const s = managedSection({ language: "en", blocks, settings: ["Use a patient tone.", "Give a hint after 2 failed tries, not before."] });
    const rules = s.indexOf("Work only inside this folder.");
    const heading = s.indexOf("### How to work with this person\n\n- Use a patient tone.\n- Give a hint after 2 failed tries, not before.\n");
    const tools = s.indexOf("### Interface tools");
    expect(rules).toBeGreaterThan(0);
    expect(heading).toBeGreaterThan(rules);
    expect(tools).toBeGreaterThan(heading);
  });

  it("D0: no settings, or none to say, is exactly today's section", () => {
    const today = managedSection({ language: "en", blocks });
    expect(managedSection({ language: "en", blocks, settings: [] })).toBe(today);
    expect(managedSection({ language: "en", blocks, settings: undefined })).toBe(today);
    expect(today).not.toContain("How to work with this person");
    expect(settingsLines(undefined)).toEqual([]);
  });
});

describe("refreshInstructions", () => {
  const opts = (folder: string, settings?: string[]) => ({ folder, base: "x", language: "en" as const, blocks, ...(settings ? { settings } : {}) });

  it("writes nothing when the text is the same, and rewrites AGENTS.md when it changed", async () => {
    const folder = tmp();
    await writeInstructions({ ...opts(folder, ["Use a patient tone."]), engine: getEngine("codex") });
    const file = path.join(folder, "AGENTS.md");
    const before = fs.statSync(file).mtimeMs;
    expect(await refreshInstructions(opts(folder, ["Use a patient tone."]))).toBe(false);
    expect(fs.statSync(file).mtimeMs).toBe(before);
    expect(await refreshInstructions(opts(folder, ["Use a demanding tone."]))).toBe(true);
    expect(fs.readFileSync(file, "utf8")).toContain("- Use a demanding tone.");
    expect(fs.readFileSync(file, "utf8")).not.toContain("patient");
  });

  it("leaves no temp file in the folder or under .harness/", async () => {
    const folder = tmp();
    await refreshInstructions(opts(folder, ["Use a patient tone."]));
    expect(fs.readdirSync(folder).sort()).toEqual([".harness", "AGENTS.md"]);
    expect(fs.readdirSync(path.join(folder, ".harness"))).toEqual([]);
  });

  it("writes the same text as writeInstructions", async () => {
    const a = tmp();
    const b = tmp();
    await writeInstructions({ ...opts(a, ["Use a patient tone."]), engine: getEngine("codex") });
    await refreshInstructions(opts(b, ["Use a patient tone."]));
    expect(fs.readFileSync(path.join(b, "AGENTS.md"), "utf8")).toBe(fs.readFileSync(path.join(a, "AGENTS.md"), "utf8"));
  });
});

describe("writing for the reader (document-reader spec §4)", () => {
  const GUIDE_START = "### Writing for the reader";

  it("D0: without `writing` the section is exactly today's", () => {
    expect(managedSection({ language: "en", blocks })).not.toContain(GUIDE_START);
  });

  it("the base guide: last part of the section, English, the six callouts and nothing else", () => {
    const s = managedSection({ language: "es", blocks: {}, writing: { kinds: {} } });
    expect(s.trimEnd().endsWith(MANAGED_END)).toBe(true);
    const guide = s.slice(s.indexOf(GUIDE_START), s.indexOf(MANAGED_END));
    expect(guide).toMatchSnapshot();
    for (const c of ["NOTE", "TIP", "WARNING", "SUMMARY", "DECISION", "QUESTION"]) expect(guide).toContain(`[!${c}]`);
    expect([...new Set(guide.match(/\[![A-Z]+\]/g))].sort()).toEqual(["[!DECISION]", "[!NOTE]", "[!QUESTION]", "[!SUMMARY]", "[!TIP]", "[!WARNING]"]);
    expect(guide).not.toContain("### Document kinds");
    expect(guide).toContain("`title` always.");
    expect(guide).not.toContain("`kind`");
  });

  it("with kinds: each kind's id, when and its template (front-matter, then headings in order)", () => {
    const s = managedSection({
      language: "en",
      blocks: {},
      writing: {
        kinds: {
          adr: { when: "A decision with real alternatives.", sections: ["Status", "Context", "Decision"], status: ["proposed", "accepted", "superseded"] },
          analysis: { when: "Exploring options before deciding.", sections: ["Context", "Options"] },
        },
      },
    });
    const kinds = s.slice(s.indexOf("### Document kinds"), s.indexOf(MANAGED_END));
    expect(kinds).toMatchSnapshot();
    expect(kinds).toContain("- `adr`: A decision with real alternatives.");
    expect(kinds).toContain("    status: proposed | accepted | superseded");
    expect(kinds.indexOf("    ## Status")).toBeLessThan(kinds.indexOf("    ## Decision"));
    expect(s).toContain("`title` always, and `kind` when one of the kinds below fits.");
  });

  it("a kind's template is a code block inside its list item, so its headings never render as live headings", () => {
    const s = managedSection({ language: "en", blocks: {}, writing: { kinds: { adr: { when: "x", sections: ["Status"] } } } });
    const kinds = s.slice(s.indexOf("### Document kinds"), s.indexOf(MANAGED_END));
    // The item's content starts at column 2; a code block inside it needs 4 more spaces.
    for (const line of ["---", "title: …", "kind: adr", "## Status"]) expect(kinds).toContain(`\n      ${line}\n`);
  });
});

describe("writing guide: review lines (review spec §4)", () => {
  it("only with review", () => {
    const without = writingLines({ kinds: {} });
    const withReview = writingLines({ kinds: {}, review: true });
    const added = withReview.filter((l) => !without.includes(l));
    expect(added).toEqual([
      "- **Asking about a passage.** Use `ask_in_document`, and give for each option the full text that replaces the passage.",
      "- **Blocking questions.** Mark a question `blocking` only when the document can't be approved without its answer.",
      "- **Review rounds.** After a review round, answer every comment with `reply_to_comment`.",
    ]);
    expect(withReview.filter((l) => without.includes(l))).toEqual(without);
  });
});
