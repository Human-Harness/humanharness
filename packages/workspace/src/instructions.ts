/** A folder the agent may read but never change, with the label the instructions show. */
export interface ReferenceFolder {
  label: string;
  path: string;
}

/** A linked folder as the managed section names it (hatches spec §3.3). */
export interface LinkedFolderLine {
  key: string;
  label: string;
  path: string;
  mode: "read" | "write";
}

/** Folds line breaks to spaces: a label or path can't start a line of its own in the section. */
const oneLine = (s: string) => s.replace(/[\r\n]+/g, " ");

function toolSchema(schema: Block["schema"]): string {
  const { $schema: _omit, ...rest } = z.toJSONSchema(schema) as Record<string, unknown>;
  return JSON.stringify(rest);
}

/** The settings' lines of the managed section (harness-settings spec §5): none without sentences (D0). */
export function settingsLines(sentences: readonly string[] | undefined): string[] {
  return sentences && sentences.length > 0 ? ["", TEXT.settings, "", ...sentences.map((s) => `- ${s}`)] : [];
}

/** What `AGENTS.md` says about writing documents (document-reader spec §4.1, §4.2). */
export interface WritingGuide {
  /** The harness's document kinds; `{}` for the base guide only. */
  kinds: Record<string, DocumentKind>;
  /** The agent has the review tools (review spec §4): three more rules. Absent: none (D0). */
  review?: boolean;
}

/** The "Writing for the reader" part, and with kinds the "Document kinds" part. None without a guide. */
export function writingLines(writing: WritingGuide | undefined): string[] {
  if (!writing) return [];
  const t = TEXT;
  const kinds = Object.entries(writing.kinds);
  const rules = t.writingRules(kinds.length > 0).map((r) => (r.startsWith("  ") ? r : `- ${r}`));
  if (writing.review) rules.push(...t.reviewRules.map((r) => `- ${r}`));
  const lines = ["", t.writing, "", t.writingIntro, "", ...rules, "", ...t.writingExample];
  if (kinds.length === 0) return lines;
  lines.push("", t.kinds, "", t.kindsIntro);
  for (const [id, k] of kinds) {
    // Six spaces: a code block inside the list item (content at column 2), so `## …` stays text.
    const code = "      ";
    lines.push("", `- \`${id}\`: ${k.when}`, `  ${t.kindTemplate}`, "", `${code}---`, `${code}title: …`, `${code}kind: ${id}`);
    if (k.status) lines.push(`${code}status: ${k.status.join(" | ")}`);
    lines.push(`${code}---`, ...k.sections.map((s) => `${code}## ${s}`));
  }
  return lines;
}

export function managedSection(opts: {
  language: Language;
  blocks: Record<string, Block>;
  references?: ReferenceFolder[];
  settings?: readonly string[];
  material?: boolean;
  /** The writing guide (document-reader spec D4). Absent: no such part (callers that predate it). */
  writing?: WritingGuide;
  /** The open scope's linked folders (hatches spec §3.3). Absent or empty: no such part, the old folder rule (D0). */
  linked?: readonly LinkedFolderLine[];
}): string {
  const t = TEXT;
  const linked = opts.linked ?? [];
  const lines = [MANAGED_START, t.title, "", ...t.rules(opts.language, linked.length > 0).map((r) => `- ${r}`), ...settingsLines(opts.settings)];
  const entries = Object.entries(opts.blocks);
  if (entries.length > 0) {
    lines.push("", t.tools, "", t.toolsIntro, "");
    for (const [name, block] of entries) {
      lines.push(
        `- \`${blockToolName(name, block)}\`: ${block.description}`,
        `  ${t.example}: \`${JSON.stringify(block.example)}\``,
        `  ${t.schema}: \`${toolSchema(block.schema)}\``,
      );
      // The header names the block, not its tool: a block with its own `tool` name shows the link here.
      if (block.input) lines.push(`  ${t.answer} (\`${answerHeader(name)}\`): \`${toolSchema(block.input)}\``);
    }
    // Only a harness with input blocks gets the answers section (spec D0).
    if (entries.some(([, b]) => b.input)) {
      lines.push("", t.answers, "", ...t.answerRules.map((r) => `- ${r}`));
      if (Object.hasOwn(opts.blocks, "annotate")) lines.push(`- ${t.annotateRule}`);
    }
  }
  const references = opts.references ?? [];
  if (references.length > 0) {
    lines.push("", t.references, "", t.referencesIntro, "");
    for (const r of references) lines.push(`- ${r.label}: \`${r.path}\``);
  }
  if (linked.length > 0) {
    lines.push("", t.linked, "", t.linkedIntro, "");
    for (const l of linked) {
      lines.push(`- \`${oneLine(l.key)}\` (${oneLine(l.label)}, ${l.mode === "write" ? "read and write" : "read only"}): \`${oneLine(l.path)}\``);
    }
  }
  // Only a harness with material gets this part (material spec D0).
  if (opts.material) lines.push("", t.material, "", ...t.materialRules.map((r) => `- ${r}`));
  lines.push(...writingLines(opts.writing));
  lines.push(MANAGED_END, "");
  return lines.join("\n");
}

/** The files the app generates in the folder for an engine: AGENTS.md and the engine's own instructions file. */
export function generatedFiles(engine: EngineDef): string[] {
  return ["AGENTS.md", ...(engine.instructionsFile ? [engine.instructionsFile.path] : [])];
}

/** What AGENTS.md holds: the harness's base, then the managed section. */
export interface InstructionsText {
  base: string;
  language: Language;
  blocks: Record<string, Block>;
  references?: ReferenceFolder[];
  /** The harness's settings as sentences (harness-settings spec §5). Absent or empty: no section (D0). */
  settings?: readonly string[];
  /** The harness takes material: the Material part. Absent: none (D0). */
  material?: boolean;
  /** The writing guide; the runtime always passes it (document-reader spec D4). */
  writing?: WritingGuide;
  /** The open scope's linked folders (hatches spec §3.3). Absent or empty: none (D0). */
  linked?: readonly LinkedFolderLine[];
}

function agentsText(opts: InstructionsText): string {
  const section = managedSection({
    language: opts.language,
    blocks: opts.blocks,
    references: opts.references,
    settings: opts.settings,
    material: opts.material,
    writing: opts.writing,
    linked: opts.linked,
  });
  return `${opts.base.trimEnd()}\n\n${section}`;
}

/** Writes AGENTS.md (harness base + managed section) and the engine's own file. Returns the relative paths written. */
export async function writeInstructions(opts: InstructionsText & { folder: string; engine: EngineDef }): Promise<string[]> {
  const extraPath = opts.engine.instructionsFile?.path;
  if (extraPath !== undefined && path.basename(extraPath) !== extraPath) {
    throw new Error(`Engine instructions file must be a plain file name, got "${extraPath}"`);
  }
  await fs.mkdir(opts.folder, { recursive: true });
  await fs.writeFile(path.join(opts.folder, "AGENTS.md"), agentsText(opts));
  const extra = opts.engine.instructionsFile;
  if (extra) await fs.writeFile(path.join(opts.folder, extra.path), extra.content);
  return generatedFiles(opts.engine);
}

/**
 * Rewrites AGENTS.md between tasks when its text changed (harness-settings spec §5). Identical text is left alone,
 * so the engine's cached prefix survives. The new text goes to a temp file under `.harness/` (which the history
 * ignores) and is renamed over AGENTS.md: a session or a commit made meanwhile never sees half a file. True when it wrote.
 */
export async function refreshInstructions(opts: InstructionsText & { folder: string }): Promise<boolean> {
  const file = path.join(opts.folder, "AGENTS.md");
  const text = agentsText(opts);
  const current = await fs.readFile(file, "utf8").catch(() => null);
  if (current === text) return false;
  const dir = harnessDir(opts.folder);
  await fs.mkdir(dir, { recursive: true });
  const tmp = path.join(dir, `AGENTS.md.${randomUUID()}.tmp`);
  try {
    await fs.writeFile(tmp, text);
    await fs.rename(tmp, file);
  } catch (err) {
    await fs.rm(tmp, { force: true });
    throw err;
  }
  return true;
}
